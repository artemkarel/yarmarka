def main():
    conn = db.get()
    fake_user = {"id": 0, "role": "admin"}
    added = skipped = 0
    for district, addr in FAIRS:
        name = f"Ярмарка выходного дня ({district})"
        if conn.execute("SELECT 1 FROM points WHERE name=? AND address=?",
                        (name, addr)).fetchone():
            skipped += 1
            continue
