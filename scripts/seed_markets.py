def main():
    conn = db.get()
    fake_user = {"id": 0, "role": "admin"}
    p_add = p_skip = e_add = e_skip = 0
    for city, name, addr, comment in POINTS:
        if conn.execute("SELECT 1 FROM points WHERE name=? AND city=?",
                        (name, city)).fetchone():
            p_skip += 1
            continue
        services.point_save(conn, fake_user, None, name, "Маркет", city, addr,
                            None, comment)
        p_add += 1
    for city, name, d1, d2, comment in EVENTS:
        if conn.execute("SELECT 1 FROM events WHERE name=? AND city=? AND date_from=?",
                        (name, city, d1)).fetchone():
            e_skip += 1
            continue
        services.event_save(conn, fake_user, None, name, "Маркет", city, d1, d2,
                            None, comment)
        e_add += 1
    print(f"точки-маркеты: +{p_add} (дублей {p_skip}); "
          f"события-маркеты: +{e_add} (дублей {e_skip})")


if __name__ == "__main__":
    main()
